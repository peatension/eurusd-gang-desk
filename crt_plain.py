def check_pending(
    state,
    pair,
    ltf,
):
    """
    Manage an already-issued CRT Plain signal.

    TELEGRAM FLOW:

        ORIGINAL SIGNAL
              ↓
        TP1 HIT — HEADING TO TP2
              ↓
        TP2 HIT → FINAL VERDICT: WIN

    OR:

        ORIGINAL SIGNAL
              ↓
        SL HIT → FINAL VERDICT: LOSS

    The SAME original Telegram message is edited.

    No separate WIN/LOSS broadcast is made.
    """

    if not state["pending"] or ltf is None:
        return

    remaining = []

    latest = len(ltf) - 1

    primary = (
        str(desk.CHAT_ID)
        if desk.CHAT_ID
        else None
    )

    for trade in state["pending"]:

        if trade.get("pair") != pair:

            remaining.append(
                trade
            )

            continue

        try:

            entry_time = pd.Timestamp(
                trade["candle_time"]
            )

            matches = np.where(
                ltf["datetime"].values
                >= entry_time.to_datetime64()
            )[0]

        except Exception:

            remaining.append(
                trade
            )

            continue

        if len(matches) == 0:

            remaining.append(
                trade
            )

            continue

        signal_index = int(
            matches[0]
        )

        last_checked = int(
            trade.get(
                "last_checked_index",
                signal_index,
            )
        )

        start = max(
            signal_index + 1,
            last_checked + 1,
        )

        direction = int(
            trade["direction"]
        )

        stop = float(
            trade["stop"]
        )

        tp1 = float(
            trade["tp1"]
        )

        tp2 = float(
            trade["tp2"]
        )

        edit_chat = (
            trade.get(
                "edit_chat_id"
            )
            or primary
        )

        closed = False

        for j in range(
            start,
            latest + 1,
        ):

            high = float(
                ltf["high"].iloc[j]
            )

            low = float(
                ltf["low"].iloc[j]
            )

            candle_time = str(
                ltf["datetime"].iloc[j]
            )

            trade[
                "last_checked_index"
            ] = j

            if direction == 1:

                hit_sl = (
                    low <= stop
                )

                hit_tp2 = (
                    high >= tp2
                )

                hit_tp1 = (
                    high >= tp1
                )

            else:

                hit_sl = (
                    high >= stop
                )

                hit_tp2 = (
                    low <= tp2
                )

                hit_tp1 = (
                    low <= tp1
                )

            # =================================================
            # SL
            # =================================================
            #
            # Candle-level priority is preserved:
            # SL is checked before TP2 because OHLC data alone
            # cannot establish which level was touched first
            # when both are inside the same candle.
            #

            if hit_sl:

                message = (
                    _outcome_status_message(
                        trade,
                        "LOSS",
                        candle_time,
                        -1.0,
                    )
                )

                edited = desk.edit_telegram(
                    trade.get(
                        "message_id"
                    ),
                    message,
                    edit_chat,
                )

                if not edited:

                    print(
                        "CRT Plain LOSS "
                        "message edit failed:",
                        trade.get("pair"),
                        trade.get("stream"),
                    )

                _log_completed_trade(
                    trade,
                    "LOSS",
                    -1.0,
                    candle_time,
                )

                closed = True

                break

            # =================================================
            # TP1
            # =================================================
            #
            # TP1 does NOT close the trade.
            #

            if (
                hit_tp1
                and not trade.get(
                    "tp1_hit",
                    False,
                )
            ):

                trade[
                    "tp1_hit"
                ] = True

                trade[
                    "tp1_time"
                ] = candle_time

                edited = desk.edit_telegram(
                    trade.get(
                        "message_id"
                    ),
                    _tp1_status_message(
                        trade
                    ),
                    edit_chat,
                )

                if not edited:

                    print(
                        "CRT Plain TP1 "
                        "message edit failed:",
                        trade.get("pair"),
                        trade.get("stream"),
                    )

            # =================================================
            # TP2
            # =================================================
            #
            # TP2 = FINAL WIN.
            #

            if hit_tp2:

                # If the same candle reaches TP1 and TP2,
                # record TP1 as reached before finalizing.
                if not trade.get(
                    "tp1_hit",
                    False,
                ):

                    trade[
                        "tp1_hit"
                    ] = True

                    trade[
                        "tp1_time"
                    ] = candle_time

                rr2 = float(
                    trade.get(
                        "rr2",
                        0.0,
                    )
                )

                message = (
                    _outcome_status_message(
                        trade,
                        "WIN",
                        candle_time,
                        rr2,
                    )
                )

                edited = desk.edit_telegram(
                    trade.get(
                        "message_id"
                    ),
                    message,
                    edit_chat,
                )

                if not edited:

                    print(
                        "CRT Plain WIN "
                        "message edit failed:",
                        trade.get("pair"),
                        trade.get("stream"),
                    )

                _log_completed_trade(
                    trade,
                    "WIN",
                    rr2,
                    candle_time,
                )

                closed = True

                break

        if not closed:

            remaining.append(
                trade
            )

    state["pending"] = remaining


