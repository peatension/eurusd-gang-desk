def _is_crt_plain_record(record):

    stream = str(
        record.get(
            "stream",
            "",
        )
    )

    return stream.startswith(
        "CRT "
    )


def _load_crt_outcomes():

    try:

        rows = desk.load_outcomes()

        if not isinstance(
            rows,
            list,
        ):
            return []

        return [
            row
            for row in rows
            if _is_crt_plain_record(
                row
            )
        ]

    except Exception as e:

        print(
            "CRT outcomes load error:",
            e,
        )

        return []


def _record_signal_time(row):

    for key in (
        "signal_time",
        "candle_time",
        "entry_time",
        "time",
    ):

        value = row.get(key)

        if value:

            ts = _parse_utc(
                value
            )

            if ts is not None:
                return ts

    return None


def _record_session(row):

    stored = row.get(
        "session"
    )

    if stored:
        return str(
            stored
        )

    return _session_for_utc(
        _record_signal_time(row)
    )


