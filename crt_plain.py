def _week_close_for_date(date_obj):
    """
    Friday 21:00 UTC for the ISO week containing date_obj.
    """

    monday = (
        date_obj
        - timedelta(
            days=date_obj.weekday()
        )
    )

    friday = (
        monday
        + timedelta(days=4)
    )

    return datetime(
        friday.year,
        friday.month,
        friday.day,
        WEEK_CLOSE_UTC_HOUR,
        0,
        0,
        tzinfo=timezone.utc,
    )


def _previous_week_window(now_utc):

    current_monday = (
        now_utc.date()
        - timedelta(
            days=now_utc.weekday()
        )
    )

    previous_monday = (
        current_monday
        - timedelta(days=7)
    )

    week_start = datetime(
        previous_monday.year,
        previous_monday.month,
        previous_monday.day,
        0,
        0,
        0,
        tzinfo=timezone.utc,
    )

    week_close = _week_close_for_date(
        previous_monday
    )

    iso = previous_monday.isocalendar()

    week_key = (
        f"{iso.year}-W{iso.week:02d}"
    )

    return (
        week_start,
        week_close,
        week_key,
    )


def _previous_month_window(now_utc):

    first_current = datetime(
        now_utc.year,
        now_utc.month,
        1,
        0,
        0,
        0,
        tzinfo=timezone.utc,
    )

    previous_last = (
        first_current
        - timedelta(seconds=1)
    )

    start = datetime(
        previous_last.year,
        previous_last.month,
        1,
        0,
        0,
        0,
        tzinfo=timezone.utc,
    )

    close = datetime(
        previous_last.year,
        previous_last.month,
        previous_last.day,
        23,
        59,
        59,
        tzinfo=timezone.utc,
    )

    key = (
        f"{start.year}-"
        f"{start.month:02d}"
    )

    return (
        start,
        close,
        key,
    )


def _previous_year_window(now_utc):

    year = now_utc.year - 1

    start = datetime(
        year,
        1,
        1,
        0,
        0,
        0,
        tzinfo=timezone.utc,
    )

    close = datetime(
        year,
        12,
        31,
        23,
        59,
        59,
        tzinfo=timezone.utc,
    )

    return (
        start,
        close,
        str(year),
    )


