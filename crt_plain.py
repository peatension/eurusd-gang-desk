def _telegram_available():

    try:

        if desk.CHAT_ID:
            return True

        subscribers = (
            desk.load_subscribers()
        )

        return bool(
            subscribers
        )

    except Exception:

        return False


def _send_once(
    state,
    state_key,
    period_key,
    report,
    label,
):

    if state.get(
        state_key
    ) == period_key:

        return False

    if not _telegram_available():

        print(
            f"CRT {label} report "
            f"not sent — no Telegram "
            f"subscribers."
        )

        return False

    try:

        message_id = desk.broadcast(
            report
        )

    except Exception as e:

        print(
            f"CRT {label} report "
            f"broadcast error:",
            e,
        )

        return False

    if not message_id:

        print(
            f"CRT {label} report "
            f"not confirmed sent."
        )

        return False

    state[
        state_key
    ] = period_key

    print(
        f"CRT {label} report sent: "
        f"{period_key}"
    )

    return True


def maybe_send_weekly_report(
    state,
    now_utc=None,
):

    """
    Weekly report:

    Released on Saturday only.

    Covers:
      Previous Monday 00:00 UTC
      through Friday 21:00 UTC
    """

    now_utc = (
        now_utc
        or datetime.now(
            timezone.utc
        )
    )

    if now_utc.weekday() != 5:
        return

    (
        start,
        close,
        week_key,
    ) = _previous_week_window(
        now_utc
    )

    if now_utc < close:
        return

    rows = _load_crt_outcomes()

    metrics = _performance_metrics(
        rows,
        start,
        close,
    )

    report = _build_report(
        "WEEKLY PERFORMANCE OVERVIEW",
        week_key,
        start,
        close,
        metrics,
    )

    _send_once(
        state,
        "last_weekly_report",
        week_key,
        report,
        "weekly",
    )


