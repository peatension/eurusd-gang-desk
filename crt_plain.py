def _parse_utc(value):
    try:
        ts = pd.Timestamp(value)

        if ts.tzinfo is None:
            return ts.tz_localize("UTC")

        return ts.tz_convert("UTC")

    except Exception:
        return None


def _format_dual_time(value, include_date=True):
    """
    Required display:

    🇳🇬 WAT = UTC+1, 12-hour AM/PM
    🌐 UTC = 24-hour
    """

    ts = _parse_utc(value)

    if ts is None:
        return "🇳🇬 n/a WAT · 🌐 n/a UTC"

    wat = ts + pd.Timedelta(hours=1)

    wat_text = wat.strftime("%I:%M %p").lstrip("0")
    utc_text = ts.strftime("%H:%M")

    if include_date:
        date_text = wat.strftime("%d %b %Y")

        return (
            f"🇳🇬 {wat_text} WAT · "
            f"🌐 {utc_text} UTC · {date_text}"
        )

    return (
        f"🇳🇬 {wat_text} WAT · "
        f"🌐 {utc_text} UTC"
    )


def _session_for_utc(value):
    """
    Fixed UTC session buckets for deterministic reporting.

    Asia:
        00:00–07:59 UTC

    London:
        08:00–12:59 UTC

    New York:
        13:00–20:59 UTC
    """

    ts = _parse_utc(value)

    if ts is None:
        return "Unknown"

    hour = ts.hour

    if 0 <= hour < 8:
        return "Asia"

    if 8 <= hour < 13:
        return "London"

    return "New York"


def _session_window_text():
    return (
        "Asia 00–07 UTC · "
        "London 08–12 UTC · "
        "New York 13–20 UTC"
    )


