def _performance_metrics(
    rows,
    start,
    close,
):

    selected = []

    for row in rows:

        exit_ts = _parse_utc(
            row.get("exit_time")
            or row.get("resolved_time")
            or row.get("close_time")
        )

        if exit_ts is None:
            continue

        if (
            start
            <= exit_ts
            <= close
        ):

            selected.append(
                (
                    row,
                    exit_ts,
                )
            )

    total = len(
        selected
    )

    wins = sum(
        1
        for row, _
        in selected
        if str(
            row.get(
                "status",
                "",
            )
        ).upper()
        == "WIN"
    )

    losses = sum(
        1
        for row, _
        in selected
        if str(
            row.get(
                "status",
                "",
            )
        ).upper()
        == "LOSS"
    )

    time_exits = sum(
        1
        for row, _
        in selected
        if str(
            row.get(
                "status",
                "",
            )
        ).upper()
        == "TIME EXIT"
    )

    rs = []
    winning_rs = []
    losing_rs = []

    for row, _ in selected:

        try:

            r = float(
                row.get(
                    "result_r"
                )
            )

        except Exception:

            continue

        rs.append(r)

        if r > 0:

            winning_rs.append(
                r
            )

        elif r < 0:

            losing_rs.append(
                r
            )

    total_r = sum(
        rs
    )

    avg_r = (
        total_r / len(rs)
        if rs
        else 0.0
    )

    avg_win_r = (
        sum(winning_rs)
        / len(winning_rs)
        if winning_rs
        else 0.0
    )

    avg_loss_r = (
        sum(losing_rs)
        / len(losing_rs)
        if losing_rs
        else 0.0
    )

    gross_profit = sum(
        r
        for r in rs
        if r > 0
    )

    gross_loss_abs = abs(
        sum(
            r
            for r in rs
            if r < 0
        )
    )

    if gross_loss_abs > 0:

        profit_factor = (
            gross_profit
            / gross_loss_abs
        )

    elif gross_profit > 0:

        profit_factor = float(
            "inf"
        )

    else:

        profit_factor = 0.0

    win_rate = (
        wins / total * 100
        if total
        else 0.0
    )

    best_r = (
        max(rs)
        if rs
        else 0.0
    )

    worst_r = (
        min(rs)
        if rs
        else 0.0
    )

    tp1_touches = sum(
        1
        for row, _
        in selected
        if bool(
            row.get(
                "tp1_hit",
                False,
            )
        )
    )

    tp2_wins = sum(
        1
        for row, _
        in selected
        if str(
            row.get(
                "status",
                "",
            )
        ).upper()
        == "WIN"
    )

    pairs = {}
    streams = {}
    sessions = {}
    session_r = {}
    session_trades = {}

    for row, _ in selected:

        pair = str(
            row.get(
                "pair",
                "Unknown",
            )
        )

        stream = str(
            row.get(
                "stream",
                "Unknown",
            )
        )

        session = _record_session(
            row
        )

        pairs[pair] = (
            pairs.get(
                pair,
                0,
            )
            + 1
        )

        streams[stream] = (
            streams.get(
                stream,
                0,
            )
            + 1
        )

        sessions[session] = (
            sessions.get(
                session,
                0,
            )
            + 1
        )

        try:

            r = float(
                row.get(
                    "result_r"
                )
            )

        except Exception:

            r = 0.0

        session_r[session] = (
            session_r.get(
                session,
                0.0,
            )
            + r
        )

        session_trades[session] = (
            session_trades.get(
                session,
                0,
            )
            + 1
        )

    return {
        "total": total,
        "wins": wins,
        "losses": losses,
        "time_exits": time_exits,
        "win_rate": win_rate,
        "total_r": total_r,
        "avg_r": avg_r,
        "avg_win_r": avg_win_r,
        "avg_loss_r": avg_loss_r,
        "profit_factor": profit_factor,
        "best_r": best_r,
        "worst_r": worst_r,
        "tp1_touches": tp1_touches,
        "tp2_wins": tp2_wins,
        "pairs": pairs,
        "streams": streams,
        "sessions": sessions,
        "session_r": session_r,
        "session_trades": session_trades,
    }


def _performance_verdict(m):

    if m["total"] == 0:

        return (
            "⚪ NO TRADES",
            "No completed CRT Plain "
            "trades in this period.",
        )

    if (
        m["total_r"] >= 5
        and m["win_rate"] >= 60
    ):

        return (
            "🟢 VERY NICE PERIOD",
            "Strong positive recorded R "
            "with a solid recorded win rate.",
        )

    if (
        m["total_r"] >= 2
        and m["win_rate"] >= 50
    ):

        return (
            "🟢 GOOD PERIOD",
            "Positive recorded R with at "
            "least half of trades winning.",
        )

    if m["total_r"] > 0:

        return (
            "🟡 POSITIVE PERIOD",
            "The completed sample finished "
            "above zero R.",
        )

    if m["total_r"] == 0:

        return (
            "🟡 MIXED PERIOD",
            "The completed sample finished "
            "around breakeven.",
        )

    if m["total_r"] <= -5:

        return (
            "🔴 VERY BAD PERIOD",
            "Large negative recorded R "
            "in the completed sample.",
        )

    return (
        "🔴 BAD PERIOD",
        "The completed sample finished "
        "below zero R.",
    )


def _format_distribution(data):

    if not data:
        return "• None"

    return "\n".join(
        f"• {name}: {count}"
        for name, count
        in sorted(
            data.items(),
            key=lambda item: (
                -item[1],
                item[0],
            ),
        )
    )


def _format_session_performance(
    metrics
):

    if not metrics[
        "session_trades"
    ]:

        return "• None"

    rows = []

    for (
        session,
        trades,
    ) in sorted(
        metrics[
            "session_trades"
        ].items(),
        key=lambda item: (
            -item[1],
            item[0],
        ),
    ):

        total_r = metrics[
            "session_r"
        ].get(
            session,
            0.0,
        )

        rows.append(
            f"• {session}: "
            f"{trades} trades | "
            f"{total_r:+.2f}R"
        )

    return "\n".join(
        rows
    )


