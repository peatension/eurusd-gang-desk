def find_setup(htf, pip):
    """
    Latest closed C2 only.

    C2 must sweep C1 and close back inside.
    """

    if htf is None or len(htf) < 5:
        return None

    c2 = htf.iloc[-2]
    c1 = htf.iloc[-3]

    crh = float(c1["high"])
    crl = float(c1["low"])

    mid = (crh + crl) / 2.0

    if crh - crl < 5 * pip:
        return None

    # Bullish CRT
    if (
        float(c2["low"]) < crl
        and crl < float(c2["close"]) < crh
    ):
        return {
            "crh": crh,
            "crl": crl,
            "mid": mid,
            "extreme": float(c2["low"]),
            "direction": 1,
            "c2_time": str(c2["datetime"]),
        }

    # Bearish CRT
    if (
        float(c2["high"]) > crh
        and crl < float(c2["close"]) < crh
    ):
        return {
            "crh": crh,
            "crl": crl,
            "mid": mid,
            "extreme": float(c2["high"]),
            "direction": -1,
            "c2_time": str(c2["datetime"]),
        }

    return None


def ltf_entry(ltf, setup):
    """
    First LTF close back inside C1 after C2.

    The first qualifying LTF close is used.
    """

    if ltf is None or len(ltf) < 10:
        return None

    c2_time = pd.Timestamp(setup["c2_time"])

    after = ltf[
        ltf["datetime"] > c2_time
    ]

    if after.empty:
        return None

    crh = setup["crh"]
    crl = setup["crl"]

    for _, row in after.iterrows():

        close = float(row["close"])

        if crl < close < crh:
            return row

    return None


def analyze(
    stream_label,
    htf_name,
    ltf_name,
    htf,
    ltf,
    pair,
    pip,
):
    setup = find_setup(
        htf,
        pip,
    )

    if setup is None:
        return None

    bar = ltf_entry(
        ltf,
        setup,
    )

    if bar is None:
        return None

    if (
        "atr" in bar
        and not pd.isna(bar["atr"])
    ):
        atr = float(bar["atr"])
    else:
        atr = 0.0

    buf = max(
        1.5 * pip,
        0.25 * atr
        if atr > 0
        else 1.5 * pip,
    )

    direction = setup["direction"]

    if direction == 1:

        entry = setup["crl"]

        stop = (
            setup["extreme"]
            - buf
        )

        tp1 = setup["mid"]
        tp2 = setup["crh"]

    else:

        entry = setup["crh"]

        stop = (
            setup["extreme"]
            + buf
        )

        tp1 = setup["mid"]
        tp2 = setup["crl"]

    risk = abs(
        entry - stop
    )

    if risk <= 0:
        return None

    rr1 = abs(
        tp1 - entry
    ) / risk

    rr2 = abs(
        tp2 - entry
    ) / risk

    if rr1 < MIN_RR:
        return None

    candle_time = str(
        bar["datetime"]
    )

    return {
        "stream": stream_label,
        "pair": pair,
        "direction": direction,
        "side": (
            "BUY"
            if direction == 1
            else "SELL"
        ),
        "entry": float(entry),
        "stop": float(stop),
        "tp1": float(tp1),
        "tp2": float(tp2),
        "rr1": float(rr1),
        "rr2": float(rr2),
        "risk_pips": float(
            risk / pip
        ),
        "crh": setup["crh"],
        "crl": setup["crl"],
        "mid": setup["mid"],
        "candle_time": candle_time,
        "session": _session_for_utc(
            candle_time
        ),
        "candle_key": (
            f"{stream_label}|"
            f"{pair}|"
            f"{setup['c2_time']}|"
            f"{direction}"
        ),
        "c1_tf": htf_name,
        "ltf": ltf_name,
    }


