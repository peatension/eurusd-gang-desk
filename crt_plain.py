def _log_completed_trade(
    trade,
    status,
    result_r,
    exit_time,
):
    """
    Write the completed CRT Plain trade to the shared
    outcomes.json through 3c_model.py.

    IMPORTANT:
    This records the outcome only.

    It does NOT send Telegram messages.
    """

    record = {
        "stream": trade.get(
            "stream"
        ),
        "pair": trade.get(
            "pair"
        ),
        "side": trade.get(
            "side"
        ),
        "status": status,
        "result_r": (
            float(result_r)
            if result_r is not None
            else None
        ),
        "exit_time": exit_time,

        "entry": trade.get(
            "entry"
        ),
        "stop": trade.get(
            "stop"
        ),
        "tp1": trade.get(
            "tp1"
        ),
        "tp2": trade.get(
            "tp2"
        ),
        "rr1": trade.get(
            "rr1"
        ),
        "rr2": trade.get(
            "rr2"
        ),

        "candle_time": trade.get(
            "candle_time"
        ),

        "signal_time": trade.get(
            "signal_time",
            trade.get("candle_time"),
        ),

        "session": trade.get(
            "session"
        ),

        "tp1_hit": bool(
            trade.get(
                "tp1_hit",
                False,
            )
        ),

        "tp1_time": trade.get(
            "tp1_time"
        ),

        "tp2_hit": (
            status == "WIN"
        ),
    }

    try:

        desk.log_outcome(
            record
        )

    except Exception as e:

        print(
            "CRT Plain outcome log error:",
            e,
        )


